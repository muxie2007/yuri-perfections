-- Baseline: the four tables that were first made by hand in the Supabase dashboard
-- (before this repo kept migrations). On the live project they already exist, so every
-- statement here is a no-op there; on a fresh project it rebuilds them as they were.
-- Column shapes read from the live REST API on 2026-11-03.

create table if not exists public.hero_slides (
  id bigint generated by default as identity primary key,
  image_url text not null,
  alt_text text not null default '',
  "order" integer not null default 0,
  status text not null default 'active',
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  icon text not null default 'FiBox',
  title text not null,
  description text not null default '',
  image_url text not null default '',
  "order" integer not null default 0,
  status text not null default 'active',
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  style text not null default '',
  category text not null default '',
  location text not null default '',
  description text not null default '',
  cover_before text not null default '',
  cover_after text not null default '',
  "order" integer not null default 0,
  status text not null default 'active',
  created_at timestamptz not null default now()
);

create table if not exists public.project_images (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  before text not null,
  after text not null,
  label text not null default '',
  "order" integer not null default 0,
  created_at timestamptz not null default now()
);

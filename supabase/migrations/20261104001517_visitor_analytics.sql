-- Visitor statistics for the dashboard: one row per page view on the public site.
-- Anonymous: no IP address, no cookies set by us beyond a random id in the visitor's own
-- browser storage. Country comes from Vercel's edge (x-vercel-ip-country), the source from
-- the referrer or ?utm_source. See docs/analytics.md.

create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  path text not null check (char_length(path) between 1 and 300),
  referrer_host text not null default '' check (char_length(referrer_host) <= 200),
  source text not null default 'Direct' check (char_length(source) between 1 and 40),
  country text not null default '' check (char_length(country) <= 2),
  device text not null default 'desktop' check (device in ('mobile', 'tablet', 'desktop')),
  visitor_id uuid not null,
  session_id uuid not null,
  is_entry boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists page_views_created_idx on public.page_views (created_at desc);

alter table public.page_views enable row level security;

drop policy if exists "anyone records a page view" on public.page_views;
create policy "anyone records a page view" on public.page_views
  for insert to anon, authenticated
  with check (char_length(path) > 0 and created_at > now() - interval '1 minute');

drop policy if exists "staff read page views" on public.page_views;
create policy "staff read page views" on public.page_views
  for select to authenticated using ((select private.is_admin()));

grant insert on public.page_views to anon, authenticated;
grant select on public.page_views to authenticated;

-- Everything the Visitors screen shows, in one call. Security invoker: RLS applies, so only
-- staff get numbers. Days are counted in the business's timezone (Kampala).
create or replace function public.visitor_stats(days integer default 30)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  with bounds as (
    select greatest(1, least(coalesce(days, 30), 366)) as n
  ),
  v as (
    select pv.*, (pv.created_at at time zone 'Africa/Kampala')::date as day
    from public.page_views pv, bounds
    where pv.created_at >= (date_trunc('day', now() at time zone 'Africa/Kampala') - make_interval(days => bounds.n - 1))
                           at time zone 'Africa/Kampala'
  ),
  calendar as (
    select generate_series(
      (now() at time zone 'Africa/Kampala')::date - ((select n from bounds) - 1),
      (now() at time zone 'Africa/Kampala')::date,
      interval '1 day'
    )::date as day
  )
  select jsonb_build_object(
    'views', (select count(*) from v),
    'visitors', (select count(distinct visitor_id) from v),
    'visits', (select count(distinct session_id) from v),
    'daily', (
      select coalesce(jsonb_agg(jsonb_build_object('day', c.day, 'views', coalesce(d.views, 0), 'visitors', coalesce(d.visitors, 0)) order by c.day), '[]'::jsonb)
      from calendar c
      left join (select day, count(*) as views, count(distinct visitor_id) as visitors from v group by day) d on d.day = c.day
    ),
    'pages', (
      select coalesce(jsonb_agg(p), '[]'::jsonb)
      from (select path, count(*) as views from v group by path order by 2 desc, 1 limit 10) p
    ),
    'sources', (
      select coalesce(jsonb_agg(s), '[]'::jsonb)
      from (select source, count(*) as visits from v where is_entry group by source order by 2 desc, 1 limit 10) s
    ),
    'countries', (
      select coalesce(jsonb_agg(c), '[]'::jsonb)
      from (select country, count(distinct visitor_id) as visitors from v group by country order by 2 desc, 1 limit 15) c
    ),
    'devices', (
      select coalesce(jsonb_agg(d), '[]'::jsonb)
      from (select device, count(distinct visitor_id) as visitors from v group by device order by 2 desc) d
    )
  );
$$;

revoke execute on function public.visitor_stats(integer) from public, anon;
grant execute on function public.visitor_stats(integer) to authenticated;

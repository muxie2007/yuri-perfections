-- Admin dashboard: staff profiles and roles, editable site content, the enquiries inbox,
-- the media bucket, and row level security for all of it.
--
-- Additive and safe to run on the live project: no table or row is dropped. The only
-- things replaced are the RLS policies of the four original tables (whatever was set by
-- hand in the dashboard), so the access rules below are the whole truth.
-- See docs/database.md.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Private schema for helpers (not exposed through the Data API)
-- ─────────────────────────────────────────────────────────────────────────────
create schema if not exists private;

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Staff profiles: one per auth user, role super_admin | admin
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  full_name text not null default '',
  role text not null default 'admin' check (role in ('super_admin', 'admin')),
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function private.set_updated_at();

-- Who may manage content: an active profile with either role.
create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_active and role in ('super_admin', 'admin')
  );
$$;

-- Who may manage staff accounts.
create or replace function private.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_active and role = 'super_admin'
  );
$$;

-- A new auth user gets a profile. The role comes from app_metadata (only settable with the
-- secret key, never by the user); without one the profile is inactive and has no access.
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  wanted text := new.raw_app_meta_data ->> 'role';
begin
  insert into public.profiles (id, email, full_name, role, is_active)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    case when wanted in ('super_admin', 'admin') then wanted else 'admin' end,
    coalesce(wanted in ('super_admin', 'admin'), false)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- Users that existed before this migration: inactive until a super admin turns them on.
insert into public.profiles (id, email, full_name, role, is_active)
select u.id, coalesce(u.email, ''), coalesce(u.raw_user_meta_data ->> 'full_name', ''), 'admin', false
from auth.users u
on conflict (id) do nothing;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Projects: categories table, featured flag, completion date
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.project_categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  tagline text not null default '',
  "order" integer not null default 0,
  created_at timestamptz not null default now()
);

update public.projects set category = 'Other' where coalesce(trim(category), '') = '';

insert into public.project_categories (name, "order")
select category, row_number() over (order by min("order"))
from public.projects
group by category
on conflict (name) do nothing;

-- Renaming a category renames it on its projects; a category in use cannot be deleted.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'projects_category_fkey') then
    alter table public.projects
      add constraint projects_category_fkey foreign key (category)
      references public.project_categories (name) on update cascade on delete restrict;
  end if;
end;
$$;

alter table public.projects add column if not exists featured boolean not null default false;
alter table public.projects add column if not exists completed_on date;
alter table public.projects add column if not exists updated_at timestamptz not null default now();

drop trigger if exists projects_set_updated_at on public.projects;
create trigger projects_set_updated_at
  before update on public.projects
  for each row execute function private.set_updated_at();

-- Until the owner picks, the first four projects are featured on the home page.
update public.projects set featured = true
where id in (select id from public.projects where status = 'active' order by "order" limit 4)
  and not exists (select 1 from public.projects where featured);

create index if not exists projects_status_order_idx on public.projects (status, "order", id);
create index if not exists projects_category_idx on public.projects (category);
create index if not exists project_images_project_order_idx on public.project_images (project_id, "order");


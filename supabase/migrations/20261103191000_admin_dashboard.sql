-- ─────────────────────────────────────────────────────────────────────────────
-- 7. Row level security
-- ─────────────────────────────────────────────────────────────────────────────

-- Replace whatever policies were set by hand on the original tables (and make a re-run of
-- this file start clean on the new ones).
do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname from pg_policies
    where schemaname = 'public'
      and tablename in ('hero_slides', 'services', 'projects', 'project_images',
                        'project_categories', 'testimonials', 'contact_messages',
                        'site_settings', 'profiles')
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end;
$$;

alter table public.hero_slides enable row level security;
alter table public.services enable row level security;
alter table public.projects enable row level security;
alter table public.project_images enable row level security;
alter table public.project_categories enable row level security;
alter table public.testimonials enable row level security;
alter table public.contact_messages enable row level security;
alter table public.site_settings enable row level security;
alter table public.profiles enable row level security;

-- Visitors read what is active; staff read everything.
create policy "read active hero slides" on public.hero_slides
  for select to anon, authenticated
  using (status = 'active' or (select private.is_admin()));

create policy "read active services" on public.services
  for select to anon, authenticated
  using (status = 'active' or (select private.is_admin()));

create policy "read active projects" on public.projects
  for select to anon, authenticated
  using (status = 'active' or (select private.is_admin()));

create policy "read images of active projects" on public.project_images
  for select to anon, authenticated
  using (
    exists (select 1 from public.projects p where p.id = project_id and p.status = 'active')
    or (select private.is_admin())
  );

create policy "read categories" on public.project_categories
  for select to anon, authenticated using (true);

create policy "read active testimonials" on public.testimonials
  for select to anon, authenticated
  using (status = 'active' or (select private.is_admin()));

create policy "read site settings" on public.site_settings
  for select to anon, authenticated using (true);

-- Staff write site content.
do $$
declare
  t text;
begin
  foreach t in array array['hero_slides', 'services', 'projects', 'project_images',
                           'project_categories', 'testimonials']
  loop
    execute format(
      'create policy "staff insert" on public.%I for insert to authenticated with check ((select private.is_admin()))', t);
    execute format(
      'create policy "staff update" on public.%I for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()))', t);
    execute format(
      'create policy "staff delete" on public.%I for delete to authenticated using ((select private.is_admin()))', t);
  end loop;
end;
$$;

create policy "staff update settings" on public.site_settings
  for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));

-- Anyone may send an enquiry; only staff read and handle them.
create policy "anyone sends an enquiry" on public.contact_messages
  for insert to anon, authenticated
  with check (status = 'new' and read_at is null and notes = '');

create policy "staff read enquiries" on public.contact_messages
  for select to authenticated using ((select private.is_admin()));

create policy "staff update enquiries" on public.contact_messages
  for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));

create policy "staff delete enquiries" on public.contact_messages
  for delete to authenticated using ((select private.is_admin()));

-- A person reads their own profile; the super admin reads and edits everyone's.
create policy "read own profile or all as super admin" on public.profiles
  for select to authenticated
  using (id = (select auth.uid()) or (select private.is_super_admin()));

create policy "super admin updates profiles" on public.profiles
  for update to authenticated
  using ((select private.is_super_admin())) with check ((select private.is_super_admin()));

-- ─────────────────────────────────────────────────────────────────────────────
-- 8. Grants (the Data API may not expose new tables by default)
-- ─────────────────────────────────────────────────────────────────────────────
grant usage on schema private to anon, authenticated;
grant execute on function private.is_admin() to anon, authenticated;
grant execute on function private.is_super_admin() to anon, authenticated;

grant select on public.hero_slides, public.services, public.projects, public.project_images,
  public.project_categories, public.testimonials, public.site_settings to anon, authenticated;
grant insert, update, delete on public.hero_slides, public.services, public.projects,
  public.project_images, public.project_categories, public.testimonials to authenticated;
grant update on public.site_settings to authenticated;
grant insert on public.contact_messages to anon, authenticated;
grant select, update, delete on public.contact_messages to authenticated;
grant select, update on public.profiles to authenticated;

